-- =============================================================================
-- 50_dwh/01_dimensions.sql                                  DWH (GOLD) LAYER
-- Physical star-schema dimensions. Surrogate keys are IDENTITY columns
-- (BY DEFAULT, so the -1 "unknown" member can be inserted explicitly).
--   dim_date          generated calendar 1993-01-01 .. 1999-12-31
--   dim_branch        one row per district (the dataset's branch geography)  SCD1
--   dim_account       one row per account                                    SCD1
--   dim_customer      one row per client *version*                           SCD2
--   dim_channel       from trans.operation                                   SCD1
--   dim_txn_category  from trans.k_symbol                                    SCD1
-- row_hash = STANDARD_HASH of the tracked attributes; used for change detection.
-- =============================================================================

CREATE TABLE fd_dwh.dim_date (
  date_key        NUMBER(8)     NOT NULL,   -- YYYYMMDD
  full_date       DATE          NOT NULL,
  day_of_month    NUMBER(2)     NOT NULL,
  day_of_week     NUMBER(1)     NOT NULL,   -- ISO: 1 = Monday
  day_name        VARCHAR2(9)   NOT NULL,
  is_weekend      CHAR(1)       NOT NULL,
  iso_week        NUMBER(2)     NOT NULL,
  month_num       NUMBER(2)     NOT NULL,
  month_name      VARCHAR2(9)   NOT NULL,
  year_month      VARCHAR2(7)   NOT NULL,   -- YYYY-MM
  quarter_num     NUMBER(1)     NOT NULL,
  year_num        NUMBER(4)     NOT NULL,
  month_end_date  DATE          NOT NULL,
  is_month_end    CHAR(1)       NOT NULL,
  CONSTRAINT dim_date_pk PRIMARY KEY (date_key),
  CONSTRAINT dim_date_uk UNIQUE (full_date)
);

CREATE TABLE fd_dwh.dim_branch (
  branch_key              NUMBER GENERATED BY DEFAULT AS IDENTITY (START WITH 1),
  district_id             NUMBER(6)     NOT NULL,
  district_name           VARCHAR2(60)  NOT NULL,
  region                  VARCHAR2(60)  NOT NULL,
  inhabitants             NUMBER(10),
  city_cnt                NUMBER(6),
  urban_ratio_pct         NUMBER(5,1),
  avg_salary              NUMBER(10),
  unemp_rate_95           NUMBER(5,2),
  unemp_rate_96           NUMBER(5,2),
  entrepreneurs_per_1000  NUMBER(6),
  crimes_95               NUMBER(10),
  crimes_96               NUMBER(10),
  row_hash                RAW(32)       NOT NULL,
  created_batch_id        NUMBER,
  updated_batch_id        NUMBER,
  CONSTRAINT dim_branch_pk PRIMARY KEY (branch_key),
  CONSTRAINT dim_branch_nk UNIQUE (district_id)
);

CREATE TABLE fd_dwh.dim_account (
  account_key          NUMBER GENERATED BY DEFAULT AS IDENTITY (START WITH 1),
  account_id           NUMBER(10)    NOT NULL,
  district_id          NUMBER(6)     NOT NULL,
  statement_frequency  VARCHAR2(20)  NOT NULL,
  open_date            DATE          NOT NULL,
  owner_client_id      NUMBER(10),
  disponent_cnt        NUMBER(3)     NOT NULL,
  row_hash             RAW(32)       NOT NULL,
  created_batch_id     NUMBER,
  updated_batch_id     NUMBER,
  CONSTRAINT dim_account_pk PRIMARY KEY (account_key),
  CONSTRAINT dim_account_nk UNIQUE (account_id)
);

CREATE TABLE fd_dwh.dim_customer (
  customer_key      NUMBER GENERATED BY DEFAULT AS IDENTITY (START WITH 1),
  client_id         NUMBER(10)    NOT NULL,
  gender            CHAR(1),
  birth_date        DATE,
  birth_year        NUMBER(4),
  home_district_id  NUMBER(6),
  home_region       VARCHAR2(60),
  card_tier         VARCHAR2(10)  NOT NULL,   -- NONE / JUNIOR / CLASSIC / GOLD: best card held
  has_loan          CHAR(1)       NOT NULL,   -- Y when an account the client owns has a loan
  valid_from        DATE          NOT NULL,
  valid_to          DATE          NOT NULL,
  is_current        CHAR(1)       NOT NULL,
  row_hash          RAW(32)       NOT NULL,
  created_batch_id  NUMBER,
  updated_batch_id  NUMBER,
  CONSTRAINT dim_customer_pk PRIMARY KEY (customer_key),
  CONSTRAINT dim_customer_cur_ck CHECK (is_current IN ('Y', 'N')),
  CONSTRAINT dim_customer_rng_ck CHECK (valid_to >= valid_from)
);
-- At most one current version per client, enforced by the database.
CREATE UNIQUE INDEX fd_dwh.dim_customer_cur_uk
  ON fd_dwh.dim_customer (CASE WHEN is_current = 'Y' THEN client_id END);
CREATE INDEX fd_dwh.dim_customer_nk_ix ON fd_dwh.dim_customer (client_id, valid_from, valid_to);

CREATE TABLE fd_dwh.dim_channel (
  channel_key       NUMBER GENERATED BY DEFAULT AS IDENTITY (START WITH 1),
  channel_code      VARCHAR2(20)  NOT NULL,
  source_operation  VARCHAR2(40),             -- Czech code as delivered
  channel_name      VARCHAR2(60)  NOT NULL,
  channel_group     VARCHAR2(20)  NOT NULL,   -- CARD / CASH / TRANSFER / BANK_POSTED
  row_hash          RAW(32)       NOT NULL,
  CONSTRAINT dim_channel_pk PRIMARY KEY (channel_key),
  CONSTRAINT dim_channel_nk UNIQUE (channel_code)
);

CREATE TABLE fd_dwh.dim_txn_category (
  category_key      NUMBER GENERATED BY DEFAULT AS IDENTITY (START WITH 1),
  category_code     VARCHAR2(20)  NOT NULL,
  source_k_symbol   VARCHAR2(30),
  category_name     VARCHAR2(60)  NOT NULL,
  category_group    VARCHAR2(20)  NOT NULL,   -- INCOME / OBLIGATION / BANK_FEE / UNSPECIFIED
  row_hash          RAW(32)       NOT NULL,
  CONSTRAINT dim_txn_category_pk PRIMARY KEY (category_key),
  CONSTRAINT dim_txn_category_nk UNIQUE (category_code)
);

