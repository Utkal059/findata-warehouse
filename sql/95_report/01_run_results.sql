-- =============================================================================
-- 95_report/01_run_results.sql
-- Writes docs/run_results.md (Markdown on stdout): the evidence behind every
-- number quoted in the README, read straight from the warehouse.
--     bash scripts/sqlplus.sh sql/95_report/01_run_results.sql > docs/run_results.md
-- =============================================================================
SET SERVEROUTPUT ON SIZE UNLIMITED FORMAT WRAPPED FEEDBACK OFF VERIFY OFF HEADING OFF PAGESIZE 0 LINESIZE 400 TRIMOUT ON TAB OFF

DECLARE
  v_txt   VARCHAR2(4000);
  v_n     NUMBER;
  v_run   NUMBER;

  PROCEDURE p (s IN VARCHAR2 DEFAULT NULL) IS
  BEGIN
    DBMS_OUTPUT.PUT_LINE(s);
  END p;

  FUNCTION n (x IN NUMBER) RETURN VARCHAR2 IS
  BEGIN
    RETURN TO_CHAR(x, 'FM999G999G999G990', 'NLS_NUMERIC_CHARACTERS=''.,''');
  END n;

  FUNCTION amt (x IN NUMBER) RETURN VARCHAR2 IS
  BEGIN
    RETURN TO_CHAR(x, 'FM999G999G999G990D00', 'NLS_NUMERIC_CHARACTERS=''.,''');
  END amt;
BEGIN
  SELECT banner_full INTO v_txt FROM v$version WHERE ROWNUM = 1;
  p('# Run results');
  p;
  p('Generated by `sql/95_report/01_run_results.sql` on ' || TO_CHAR(SYSDATE, 'YYYY-MM-DD HH24:MI')
    || ' from the warehouse itself. Database: ' || REPLACE(v_txt, CHR(10), ' ') || '.');
  p('Do not edit by hand: `bash scripts/run.sh` regenerates it.');

  -- ------------------------------------------------------------------ batches
  p;
  p('## Batches');
  p;
  p('One batch per year-end. A batch stages the TRANS rows dated after the previous watermark and up to its as-of date.');
  p('Batches whose window is empty (as-of = watermark) were opened by the test suite''s failure drill.');
  p;
  p('| Batch | As of | Window starts after | Status | Seconds (first run) | Trans staged | Facts loaded | Loan snapshots | Fraud alerts |');
  p('|---:|---|---|---|---:|---:|---:|---:|---:|');
  FOR b IN (SELECT b.batch_id, b.as_of_date, b.wm_from, b.status,
                   (SELECT ROUND(SUM(EXTRACT(HOUR FROM (l.end_ts - l.start_ts)) * 3600
                                     + EXTRACT(MINUTE FROM (l.end_ts - l.start_ts)) * 60
                                     + EXTRACT(SECOND FROM (l.end_ts - l.start_ts))))
                      FROM fd_ops.etl_log l
                     WHERE l.batch_id = b.batch_id AND l.parent_log_id IS NULL AND l.attempt_no = 1) secs,
                   (SELECT COUNT(*) FROM fd_cln.cln_trans t WHERE t.batch_id = b.batch_id)
                     + (SELECT COUNT(*) FROM fd_cln.q_trans q WHERE q.batch_id = b.batch_id) staged,
                   (SELECT COUNT(*) FROM fd_dwh.fact_transaction f WHERE f.batch_id = b.batch_id) facts,
                   (SELECT COUNT(*) FROM fd_dwh.fact_loan_snapshot s WHERE s.batch_id = b.batch_id) snaps,
                   (SELECT COUNT(*) FROM fd_dwh.fraud_alerts a WHERE a.batch_id = b.batch_id) alerts
              FROM fd_ops.etl_batch b ORDER BY b.batch_id) LOOP
    p('| ' || b.batch_id || ' | ' || TO_CHAR(b.as_of_date, 'YYYY-MM-DD') || ' | '
      || NVL(TO_CHAR(b.wm_from, 'YYYY-MM-DD'), '(first load)') || ' | ' || b.status || ' | ' || b.secs
      || ' | ' || n(b.staged) || ' | ' || n(b.facts) || ' | ' || n(b.snaps) || ' | ' || n(b.alerts) || ' |');
  END LOOP;
  p;
  p('Replays (test T12 on the last yearly batch, the drill''s CLEAN retry) are not included in the seconds.');
  p;
  p('Seconds per step, summed over the yearly batches (attempt 1 only). STAGE and CLEAN rows include the master files,');
  p('which are reloaded in full every batch; RAW_CHECK counts every file every batch.');
  p;
  p('| Step | Seconds | Rows loaded |');
  p('|---|---:|---:|');
  FOR s IN (SELECT st.step_seq, l.step_name,
                   ROUND(SUM(EXTRACT(HOUR FROM (l.end_ts - l.start_ts)) * 3600 + EXTRACT(MINUTE FROM (l.end_ts - l.start_ts)) * 60
                             + EXTRACT(SECOND FROM (l.end_ts - l.start_ts)))) secs,
                   SUM(l.rows_loaded) loaded
              FROM fd_ops.etl_log l
              JOIN fd_ops.etl_step st ON st.step_name = l.step_name
              JOIN fd_ops.etl_batch b ON b.batch_id = l.batch_id
             WHERE l.parent_log_id IS NULL AND l.attempt_no = 1
               AND (b.wm_from IS NULL OR b.as_of_date > b.wm_from)
             GROUP BY st.step_seq, l.step_name ORDER BY st.step_seq) LOOP
    p('| ' || s.step_name || ' | ' || s.secs || ' | ' || n(s.loaded) || ' |');
  END LOOP;

  -- --------------------------------------------------------------- row counts
  p;
  p('## Row counts by layer');
  p;
  p('| Layer | Object | Rows |');
  p('|---|---|---:|');
  FOR r IN (SELECT 'RAW' l, 'ext_account' o, (SELECT COUNT(*) FROM fd_raw.ext_account) c FROM dual UNION ALL
            SELECT 'RAW', 'ext_card',     (SELECT COUNT(*) FROM fd_raw.ext_card)     FROM dual UNION ALL
            SELECT 'RAW', 'ext_client',   (SELECT COUNT(*) FROM fd_raw.ext_client)   FROM dual UNION ALL
            SELECT 'RAW', 'ext_disp',     (SELECT COUNT(*) FROM fd_raw.ext_disp)     FROM dual UNION ALL
            SELECT 'RAW', 'ext_district', (SELECT COUNT(*) FROM fd_raw.ext_district) FROM dual UNION ALL
            SELECT 'RAW', 'ext_loan',     (SELECT COUNT(*) FROM fd_raw.ext_loan)     FROM dual UNION ALL
            SELECT 'RAW', 'ext_order',    (SELECT COUNT(*) FROM fd_raw.ext_order)    FROM dual UNION ALL
            SELECT 'RAW', 'ext_trans',    (SELECT COUNT(*) FROM fd_raw.ext_trans)    FROM dual UNION ALL
            SELECT 'STG', 'stg_trans (all batches)', (SELECT COUNT(*) FROM fd_stg.stg_trans) FROM dual UNION ALL
            SELECT 'CLN', 'cln_district', (SELECT COUNT(*) FROM fd_cln.cln_district) FROM dual UNION ALL
            SELECT 'CLN', 'cln_account',  (SELECT COUNT(*) FROM fd_cln.cln_account)  FROM dual UNION ALL
            SELECT 'CLN', 'cln_client',   (SELECT COUNT(*) FROM fd_cln.cln_client)   FROM dual UNION ALL
            SELECT 'CLN', 'cln_disp',     (SELECT COUNT(*) FROM fd_cln.cln_disp)     FROM dual UNION ALL
            SELECT 'CLN', 'cln_card',     (SELECT COUNT(*) FROM fd_cln.cln_card)     FROM dual UNION ALL
            SELECT 'CLN', 'cln_loan',     (SELECT COUNT(*) FROM fd_cln.cln_loan)     FROM dual UNION ALL
            SELECT 'CLN', 'cln_order',    (SELECT COUNT(*) FROM fd_cln.cln_order)    FROM dual UNION ALL
            SELECT 'CLN', 'cln_trans',    (SELECT COUNT(*) FROM fd_cln.cln_trans)    FROM dual UNION ALL
            SELECT 'CLN', 'quarantine (all q_ tables)',
                   (SELECT COUNT(*) FROM fd_cln.q_district) + (SELECT COUNT(*) FROM fd_cln.q_account)
                 + (SELECT COUNT(*) FROM fd_cln.q_client) + (SELECT COUNT(*) FROM fd_cln.q_disp)
                 + (SELECT COUNT(*) FROM fd_cln.q_card) + (SELECT COUNT(*) FROM fd_cln.q_loan)
                 + (SELECT COUNT(*) FROM fd_cln.q_order) + (SELECT COUNT(*) FROM fd_cln.q_trans) FROM dual UNION ALL
            SELECT 'DWH', 'dim_date',         (SELECT COUNT(*) FROM fd_dwh.dim_date)                              FROM dual UNION ALL
            SELECT 'DWH', 'dim_branch',       (SELECT COUNT(*) FROM fd_dwh.dim_branch WHERE branch_key > 0)       FROM dual UNION ALL
            SELECT 'DWH', 'dim_account',      (SELECT COUNT(*) FROM fd_dwh.dim_account WHERE account_key > 0)     FROM dual UNION ALL
            SELECT 'DWH', 'dim_customer (versions)', (SELECT COUNT(*) FROM fd_dwh.dim_customer WHERE customer_key > 0) FROM dual UNION ALL
            SELECT 'DWH', 'dim_channel',      (SELECT COUNT(*) FROM fd_dwh.dim_channel WHERE channel_key > 0)     FROM dual UNION ALL
            SELECT 'DWH', 'dim_txn_category', (SELECT COUNT(*) FROM fd_dwh.dim_txn_category WHERE category_key > 0) FROM dual UNION ALL
            SELECT 'DWH', 'fact_transaction', (SELECT COUNT(*) FROM fd_dwh.fact_transaction)                      FROM dual UNION ALL
            SELECT 'DWH', 'loan_schedule (DERIVED)', (SELECT COUNT(*) FROM fd_dwh.loan_schedule)                  FROM dual UNION ALL
            SELECT 'DWH', 'fact_loan_snapshot', (SELECT COUNT(*) FROM fd_dwh.fact_loan_snapshot)                  FROM dual UNION ALL
            SELECT 'DWH', 'fraud_alerts',     (SELECT COUNT(*) FROM fd_dwh.fraud_alerts)                          FROM dual) LOOP
    p('| ' || r.l || ' | ' || r.o || ' | ' || n(r.c) || ' |');
  END LOOP;
  SELECT COUNT(*) INTO v_n FROM dba_tab_partitions WHERE table_owner = 'FD_DWH' AND table_name = 'FACT_TRANSACTION';
  p;
  p('`fact_transaction` partitions: ' || v_n || ' (one initial partition plus one INTERVAL partition per month that has data).');
  SELECT SUM(amount) INTO v_n FROM fd_dwh.fact_transaction;
  p('Total amount in `fact_transaction`: ' || amt(v_n) || ' CZK, equal to `cln_trans` (test T04).');

  -- ------------------------------------------------------------- data quality
  p;
  p('## Data quality');
  p;
  p('Distinct source rows per rule. The error log itself keeps one entry per step attempt, so a replay logs its findings again.');
  p;
  p('| Rule | Name | Severity | Rows, yearly batches | Rows, test drill batches |');
  p('|---|---|---|---:|---:|');
  FOR r IN (SELECT d.rule_code, d.rule_name, d.severity,
                   COUNT(DISTINCT CASE WHEN e.error_id IS NOT NULL AND (b.wm_from IS NULL OR b.as_of_date > b.wm_from)
                                       THEN e.source_table || ':' || e.source_key END) prod,
                   COUNT(DISTINCT CASE WHEN b.as_of_date = b.wm_from
                                       THEN e.batch_id || ':' || e.source_table || ':' || e.source_key END) drill
              FROM fd_ops.dq_rule d
              LEFT JOIN fd_ops.etl_error_log e ON e.rule_code = d.rule_code
              LEFT JOIN fd_ops.etl_batch b     ON b.batch_id = e.batch_id
             GROUP BY d.rule_code, d.rule_name, d.severity ORDER BY d.rule_code) LOOP
    p('| ' || r.rule_code || ' | ' || r.rule_name || ' | ' || r.severity || ' | ' || n(r.prod) || ' | ' || n(r.drill) || ' |');
  END LOOP;
  SELECT COUNT(*) INTO v_n FROM fd_cln.cln_trans WHERE dq_warn_codes LIKE '%R004%';
  p;
  p('R004 rows are kept (WARN) and flagged in `cln_trans.dq_warn_codes` / `fact_transaction.dq_warn_codes`: '
    || n(v_n) || ' transactions.');
  p('Drill-batch rows are the synthetic fixtures inserted by test T15; they are removed from staging and quarantine after the test.');

  -- --------------------------------------------------------------------- SCD2
  p;
  p('## Customer history (SCD2)');
  p;
  p('| Versions per client | Clients |');
  p('|---:|---:|');
  FOR r IN (SELECT v, COUNT(*) c FROM (SELECT client_id, COUNT(*) v FROM fd_dwh.dim_customer
                                         WHERE customer_key > 0 GROUP BY client_id)
             GROUP BY v ORDER BY v) LOOP
    p('| ' || r.v || ' | ' || n(r.c) || ' |');
  END LOOP;
  SELECT MIN(client_id) INTO v_n FROM (SELECT client_id FROM fd_dwh.dim_customer GROUP BY client_id HAVING COUNT(*) >= 3);
  p;
  p('Example, client ' || v_n || ':');
  p;
  p('| customer_key | card_tier | has_loan | valid_from | valid_to | is_current |');
  p('|---:|---|---|---|---|---|');
  FOR r IN (SELECT customer_key, card_tier, has_loan, valid_from, valid_to, is_current
              FROM fd_dwh.dim_customer WHERE client_id = v_n ORDER BY valid_from) LOOP
    p('| ' || r.customer_key || ' | ' || r.card_tier || ' | ' || r.has_loan || ' | '
      || TO_CHAR(r.valid_from, 'YYYY-MM-DD') || ' | ' || TO_CHAR(r.valid_to, 'YYYY-MM-DD') || ' | ' || r.is_current || ' |');
  END LOOP;

  -- ---------------------------------------------------------------- loan risk
  p;
  p('## Loan early warning (RBI SMA/NPA buckets applied as a framework to Czech data)');
  p;
  p('Classes at the last month-end, 1998-12-31 (loans still running or still overdue):');
  p;
  p('| Class | Loans | Outstanding CZK | Overdue CZK |');
  p('|---|---:|---:|---:|');
  FOR r IN (SELECT sma_class, COUNT(*) c, SUM(outstanding_amount) o, SUM(overdue_amount) d
              FROM fd_dwh.fact_loan_snapshot WHERE snapshot_date = DATE '1998-12-31'
             GROUP BY sma_class
             ORDER BY DECODE(sma_class, 'STANDARD', 0, 'SMA-0', 1, 'SMA-1', 2, 'SMA-2', 3, 4)) LOOP
    p('| ' || r.sma_class || ' | ' || n(r.c) || ' | ' || amt(r.o) || ' | ' || amt(r.d) || ' |');
  END LOOP;
  p;
  p('Worst class a loan ever reached (DERIVED from the schedule and repayments) against the status the source delivered:');
  p;
  p('| loan.status | STANDARD | SMA-0 | SMA-1 | SMA-2 | NPA | Loans |');
  p('|---|---:|---:|---:|---:|---:|---:|');
  FOR r IN (SELECT source_status_code || ' ' || source_status s,
                   SUM(CASE worst_sma_class WHEN 'STANDARD' THEN loans ELSE 0 END) c0,
                   SUM(CASE worst_sma_class WHEN 'SMA-0' THEN loans ELSE 0 END) c1,
                   SUM(CASE worst_sma_class WHEN 'SMA-1' THEN loans ELSE 0 END) c2,
                   SUM(CASE worst_sma_class WHEN 'SMA-2' THEN loans ELSE 0 END) c3,
                   SUM(CASE worst_sma_class WHEN 'NPA' THEN loans ELSE 0 END) c4,
                   SUM(loans) t
              FROM fd_mart.v_loan_status_vs_sma
             GROUP BY source_status_code, source_status ORDER BY source_status_code) LOOP
    p('| ' || r.s || ' | ' || r.c0 || ' | ' || r.c1 || ' | ' || r.c2 || ' | ' || r.c3 || ' | ' || r.c4 || ' | ' || r.t || ' |');
  END LOOP;

  -- -------------------------------------------------------------------- fraud
  p;
  p('## Transaction monitoring');
  p;
  p('| Rule | Name | Severity | Alerts | Accounts | Amount flagged CZK |');
  p('|---|---|---|---:|---:|---:|');
  FOR r IN (SELECT c.rule_code, c.rule_name, c.severity, COUNT(a.alert_id) al,
                   COUNT(DISTINCT a.account_key) ac, NVL(SUM(f.amount), 0) am
              FROM fd_dwh.rule_config c
              LEFT JOIN fd_dwh.fraud_alerts a ON a.rule_code = c.rule_code
              LEFT JOIN fd_dwh.fact_transaction f ON f.txn_key = a.txn_key
             GROUP BY c.rule_code, c.rule_name, c.severity ORDER BY c.rule_code) LOOP
    p('| ' || r.rule_code || ' | ' || r.rule_name || ' | ' || r.severity || ' | ' || n(r.al) || ' | '
      || n(r.ac) || ' | ' || amt(r.am) || ' |');
  END LOOP;
  p;
  p('Sample alerts (first alert of F01, F03 and F04), with the reason text the rule wrote:');
  p;
  p('| Alert | Rule | Account | Date | Amount CZK | Reason |');
  p('|---:|---|---:|---|---:|---|');
  FOR r IN (SELECT a.alert_id, a.rule_code, d.account_id, a.txn_date, f.amount, a.alert_reason
              FROM fd_dwh.fraud_alerts a
              JOIN fd_dwh.dim_account d      ON d.account_key = a.account_key
              JOIN fd_dwh.fact_transaction f ON f.txn_key = a.txn_key
             WHERE a.alert_id IN (SELECT MIN(alert_id) FROM fd_dwh.fraud_alerts
                                   WHERE rule_code IN ('F01', 'F03', 'F04') GROUP BY rule_code)
             ORDER BY a.rule_code) LOOP
    p('| ' || r.alert_id || ' | ' || r.rule_code || ' | ' || r.account_id || ' | ' || TO_CHAR(r.txn_date, 'YYYY-MM-DD')
      || ' | ' || amt(r.amount) || ' | ' || r.alert_reason || ' |');
  END LOOP;
  SELECT COUNT(*) INTO v_n FROM fd_ops.audit_log;
  p;
  p('Alert status changes go through `fd_dwh.close_fraud_alert`; the trigger writes them to `fd_ops.audit_log` ('
    || v_n || ' rows now; test T16 checks it inside a transaction it rolls back).');

  -- -------------------------------------------------------------------- tests
  SELECT MAX(run_id) INTO v_run FROM fd_ops.test_result;
  p;
  p('## Tests (run ' || NVL(TO_CHAR(v_run), 'none') || ')');
  p;
  p('| Test | Result | What it checks | Detail |');
  p('|---|---|---|---|');
  FOR r IN (SELECT test_code, status, description, REPLACE(detail, '|', '/') detail
              FROM fd_ops.test_result WHERE run_id = v_run ORDER BY test_code) LOOP
    p('| ' || r.test_code || ' | ' || r.status || ' | ' || r.description || ' | ' || r.detail || ' |');
  END LOOP;
END;
