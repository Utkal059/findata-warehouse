-- =============================================================================
-- 80_perf/04_perf_report.sql
-- Writes docs/performance.md (Markdown on stdout) from fd_ops.perf_result and
-- fd_ops.perf_plan. Every number in that file comes from the last run.
--     bash scripts/sqlplus.sh sql/80_perf/04_perf_report.sql > docs/performance.md
-- =============================================================================
SET SERVEROUTPUT ON SIZE UNLIMITED FORMAT WRAPPED FEEDBACK OFF VERIFY OFF HEADING OFF PAGESIZE 0 LINESIZE 400 TRIMOUT ON TAB OFF

DECLARE
  v_banner  VARCHAR2(400);
  v_rows    NUMBER;
  v_parts   NUMBER;
  v_ts      VARCHAR2(40);
  v_sql     VARCHAR2(4000);

  PROCEDURE p (s IN VARCHAR2 DEFAULT NULL) IS
  BEGIN
    DBMS_OUTPUT.PUT_LINE(s);
  END p;

  FUNCTION fmt (n IN NUMBER, f IN VARCHAR2 DEFAULT 'FM999G999G990D0') RETURN VARCHAR2 IS
  BEGIN
    RETURN TO_CHAR(n, f, 'NLS_NUMERIC_CHARACTERS=''.,''');
  END fmt;
BEGIN
  SELECT banner_full INTO v_banner FROM v$version WHERE ROWNUM = 1;
  SELECT COUNT(*) INTO v_rows FROM fd_dwh.fact_transaction;
  SELECT COUNT(*) INTO v_parts FROM dba_tab_partitions
   WHERE table_owner = 'FD_DWH' AND table_name = 'FACT_TRANSACTION';
  SELECT TO_CHAR(MAX(captured_ts), 'YYYY-MM-DD HH24:MI') INTO v_ts FROM fd_ops.perf_result;

  p('# Performance: before and after tuning');
  p;
  p('Generated by `sql/80_perf/04_perf_report.sql` from `fd_ops.perf_result` and `fd_ops.perf_plan`');
  p('(captured ' || v_ts || '). Do not edit by hand: re-run `bash scripts/run.sh` to refresh it.');
  p;
  p('## Set-up');
  p;
  p('* Database: ' || REPLACE(v_banner, CHR(10), ' ') || ', Docker image `gvenzl/oracle-free:23-slim-faststart`, 3 GB memory limit, on a laptop (WSL 2).');
  p('* `fd_dwh.fact_transaction`: ' || fmt(v_rows, 'FM999G999G990') || ' rows in ' || v_parts || ' partitions (monthly INTERVAL partitioning).');
  p('* Each query: 1 warm-up execution, then 5 timed executions that fetch every row through DBMS_SQL. The table shows the median.');
  p('  Buffer gets per execution come from `v$sql`; plans come from `DBMS_XPLAN.DISPLAY_CURSOR` (the plan that actually ran).');
  p('* **BEFORE**: the warehouse as the ETL leaves it (primary key, unique natural keys and a LOCAL index on `batch_id`), with');
  p('  optimizer statistics on FD_DWH deleted so the baseline does not depend on whether the automatic statistics job has run yet.');
  p('* **AFTER** (`sql/80_perf/03_perf_tune.sql`): LOCAL bitmap indexes on the fact''s branch, channel, category, customer and account keys;');
  p('  a B-tree on `fact_loan_snapshot (snapshot_date, sma_class)`; `DBMS_STATS.GATHER_SCHEMA_STATS(''FD_DWH'')`; `star_transformation_enabled = TRUE`.');
  p('* The SQL text is identical in both runs; a comment carrying the run label keeps the cursors separate.');
  p;
  p('## Results');
  p;
  p('| Query | Question | Rows | BEFORE median ms | AFTER median ms | BEFORE / AFTER | BEFORE buffer gets | AFTER buffer gets | Plan changed |');
  p('|---|---|---:|---:|---:|---:|---:|---:|---|');
  FOR r IN (SELECT b.query_id, b.description, b.rows_returned,
                   b.median_ms bm, a.median_ms am, b.buffer_gets_per_exec bg, a.buffer_gets_per_exec ag,
                   CASE WHEN b.plan_hash_value = a.plan_hash_value THEN 'no' ELSE 'yes' END changed
              FROM fd_ops.perf_result b
              JOIN fd_ops.perf_result a ON a.query_id = b.query_id AND a.run_label = 'AFTER'
             WHERE b.run_label = 'BEFORE'
             ORDER BY b.query_id) LOOP
    p('| ' || r.query_id || ' | ' || r.description || ' | ' || r.rows_returned || ' | ' || fmt(r.bm) || ' | '
      || fmt(r.am) || ' | ' || fmt(r.bm / NULLIF(r.am, 0), 'FM9990D00') || 'x | ' || fmt(r.bg, 'FM999G999G990')
      || ' | ' || fmt(r.ag, 'FM999G999G990') || ' | ' || r.changed || ' |');
  END LOOP;
  p;
  p('Min / max of the 5 timed runs:');
  p;
  p('| Query | BEFORE min-max ms | AFTER min-max ms |');
  p('|---|---:|---:|');
  FOR r IN (SELECT b.query_id, b.min_ms bmin, b.max_ms bmax, a.min_ms amin, a.max_ms amax
              FROM fd_ops.perf_result b
              JOIN fd_ops.perf_result a ON a.query_id = b.query_id AND a.run_label = 'AFTER'
             WHERE b.run_label = 'BEFORE'
             ORDER BY b.query_id) LOOP
    p('| ' || r.query_id || ' | ' || fmt(r.bmin) || ' - ' || fmt(r.bmax) || ' | '
      || fmt(r.amin) || ' - ' || fmt(r.amax) || ' |');
  END LOOP;
  p;
  p('## Queries and execution plans');
  FOR q IN (SELECT query_id, description, sql_text FROM fd_ops.perf_query ORDER BY query_id) LOOP
    p;
    p('### ' || q.query_id || ': ' || q.description);
    p;
    p('```sql');
    v_sql := DBMS_LOB.SUBSTR(q.sql_text, 4000, 1) || CHR(10);
    WHILE v_sql IS NOT NULL LOOP                       -- one output line per SQL line
      p(SUBSTR(v_sql, 1, INSTR(v_sql, CHR(10)) - 1));
      v_sql := SUBSTR(v_sql, INSTR(v_sql, CHR(10)) + 1);
    END LOOP;
    p('```');
    FOR lbl IN (SELECT 'BEFORE' l FROM dual UNION ALL SELECT 'AFTER' FROM dual) LOOP
      p;
      p('**' || lbl.l || '**');
      p;
      p('```text');
      -- skip the cursor header and SQL echo; start at "Plan hash value"
      FOR pl IN (SELECT plan_line FROM fd_ops.perf_plan
                  WHERE run_label = lbl.l AND query_id = q.query_id
                    AND plan_line IS NOT NULL
                    AND line_no >= NVL((SELECT MIN(line_no) FROM fd_ops.perf_plan
                                         WHERE run_label = lbl.l AND query_id = q.query_id
                                           AND plan_line LIKE 'Plan hash value%'), 1)
                  ORDER BY line_no) LOOP
        p(RTRIM(pl.plan_line));
      END LOOP;
      p('```');
    END LOOP;
  END LOOP;
END;
